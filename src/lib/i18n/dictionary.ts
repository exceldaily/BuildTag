const DICTS: Record<Locale, Dict> = { en, fr, de, es, th };

/** Translate a key with {placeholders}. Falls back to English. */
export function t(locale: Locale, key: DictKey, vars: Record<string, string | number> = {}): string {
  const raw = DICTS[locale]?.[key] ?? en[key];
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}

export function dictionary(locale: Locale): Dict {
  return DICTS[locale] ?? en;
}
